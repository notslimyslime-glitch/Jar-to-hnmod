import { HORIZON_REVISION } from "@/lib/horizon-hooks";

export type FabricMetadataBridge = {
  id: string;
  version: string;
  title: string;
  description: string;
  manifest: string;
  sources: Record<string, string>;
  limitations: string[];
};

function tomlString(value: string): string {
  return JSON.stringify(value);
}

function rustString(value: string): string {
  let result = '"';
  for (const char of value) {
    const code = char.codePointAt(0)!;
    if (char === '"') result += '\\"';
    else if (char === "\\") result += "\\\\";
    else if (char === "\n") result += "\\n";
    else if (char === "\r") result += "\\r";
    else if (char === "\t") result += "\\t";
    else if (code < 0x20 || code === 0x7f) result += `\\u{${code.toString(16)}}`;
    else result += char;
  }
  return result + '"';
}

/**
 * Translates only Fabric's display metadata into Horizon's native Mods-list
 * registration. It intentionally does not claim to port Java gameplay.
 */
export function translateFabricMetadata(input: {
  metadata: Record<string, unknown>;
  classFiles: number;
  mixinConfigs: number;
  entrypointCount: number;
  resourceFiles: number;
}): FabricMetadataBridge {
  if (input.classFiles > 0) throw new Error("This JAR contains Java classes. Gameplay translation is not part of the metadata-only bridge.");
  if (input.mixinConfigs > 0) throw new Error("This JAR declares Mixin configs. Their behavior cannot be represented by a metadata-only bridge.");
  if (input.entrypointCount > 0) throw new Error("This JAR declares Fabric entrypoints. Their Java behavior needs a real translator.");
  if (input.resourceFiles > 0) throw new Error("This JAR contains assets or data files. The metadata-only bridge cannot carry resources across.");

  const rawId = input.metadata.id;
  const rawVersion = input.metadata.version;
  if (typeof rawId !== "string" || !/^[a-z][a-z0-9_]{0,63}$/.test(rawId)) {
    throw new Error("The Fabric mod id must use lowercase letters, digits and underscores for this first translator.");
  }
  if (typeof rawVersion !== "string" || !/^[0-9A-Za-z][0-9A-Za-z.+_-]{0,63}$/.test(rawVersion)) {
    throw new Error("The Fabric mod version is missing or has unsupported characters.");
  }
  const name = typeof input.metadata.name === "string" && input.metadata.name.trim()
    ? input.metadata.name.trim()
    : rawId;
  const description = typeof input.metadata.description === "string"
    ? input.metadata.description.trim()
    : "";

  const helper = `// Generated by the metadata-only Fabric bridge. No Java code is copied or executed.
fn register_fabric_metadata_mod(mods: &mut Vec<crate::game::native_hooks::NativeMod>) {
    mods.push(crate::game::native_hooks::NativeMod {
        id: ${rustString(rawId)}.to_owned(),
        title: ${rustString(`${name} ${rawVersion}`)}.to_owned(),
        description: ${rustString(description)}.to_owned(),
        keys: Vec::new(),
    });
}
`;

  const manifest = `[mod]
id = ${tomlString(rawId)}
version = ${tomlString(rawVersion)}
priority = 100

[compatibility]
horizon_revision = ${tomlString(HORIZON_REVISION)}

[[injection]]
id = "register-mod"
hook = "mods"
hook_version = 1
kind = "HEAD"
helper = "register.rs"
bindings = [{ name = "mods", ty = "&mut Vec<crate::game::native_hooks::NativeMod>", value = "mods" }]
`;

  return {
    id: rawId,
    version: rawVersion,
    title: name,
    description,
    manifest,
    sources: { "register.rs": helper },
    limitations: [
      "Only the mod's display name, version and description are carried over.",
      "Java gameplay, assets, data files, dependencies, settings and runtime behavior are not converted.",
      "This prototype output still needs a pinned Horizon Mixins compile test before it can be called a supported conversion."
    ]
  };
}
