import hmac
import io
import os
import subprocess
import tempfile
import zipfile
from pathlib import Path

from fastapi import FastAPI, File, Header, HTTPException, UploadFile
from fastapi.responses import Response

app = FastAPI(title="Jar-to-HNMod Horizon Porter runner")
MAX_UPLOAD = 25 * 1024 * 1024
PORTER = os.getenv("HORIZON_PORTER_BIN", "/usr/local/bin/horizon-porter")
TOKEN = os.getenv("RUNNER_API_TOKEN", "")


@app.get("/health")
def health():
    return {"ok": True, "engine": "horizon-porter", "version": "0.9.2"}


@app.post("/v1/convert")
def convert(file: UploadFile = File(...), authorization: str | None = Header(default=None)):
    if not TOKEN:
        raise HTTPException(503, "Runner is not configured with an API token.")
    supplied = (authorization or "").removeprefix("Bearer ").strip()
    if not hmac.compare_digest(supplied, TOKEN):
        raise HTTPException(401, "Unauthorized.")
    if not file.filename or not file.filename.lower().endswith(".jar"):
        raise HTTPException(400, "Upload a .jar file.")

    with tempfile.TemporaryDirectory(prefix="jar-hnmod-") as temp:
        root = Path(temp)
        jar = root / "input.jar"
        total = 0
        with jar.open("wb") as target:
            while chunk := file.file.read(1024 * 1024):
                total += len(chunk)
                if total > MAX_UPLOAD:
                    raise HTTPException(413, "JAR exceeds the 25 MB limit.")
                target.write(chunk)
        if total == 0:
            raise HTTPException(400, "The uploaded JAR is empty.")
        try:
            with zipfile.ZipFile(jar) as archive:
                entries = archive.infolist()
                if len(entries) > 5000:
                    raise HTTPException(400, "JAR contains too many archive entries.")
                expanded = 0
                for entry in entries:
                    name = entry.filename
                    parts = name.rstrip("/").split("/")
                    if (not name or name.startswith(("/", "\\\\")) or "\\\\" in name
                            or any(part in ("", ".", "..") for part in parts)
                            or (parts and ":" in parts[0])):
                        raise HTTPException(400, "JAR contains an unsafe archive path.")
                    if not entry.is_dir():
                        expanded += entry.file_size
                        if expanded > 100 * 1024 * 1024:
                            raise HTTPException(413, "Expanded JAR contents exceed 100 MB.")
        except zipfile.BadZipFile:
            raise HTTPException(400, "The uploaded file is not a valid JAR/ZIP archive.")

        port_dir = root / "ported"
        packages = root / "packages"
        packages.mkdir()
        env = os.environ.copy()
        env["HORIZON_PORTER_CACHE"] = str(root / "cache")
        env["JAVA_TOOL_OPTIONS"] = "-Xms32m -Xmx384m"

        try:
            port = subprocess.run(
                [PORTER, "port", str(jar), "--out", str(port_dir)],
                cwd=root, env=env, capture_output=True, text=True, timeout=75,
            )
            if port.returncode != 0:
                detail = (port.stderr or port.stdout or "Horizon Porter could not port this JAR.")[-5000:]
                raise HTTPException(422, detail)
            pack = subprocess.run(
                [PORTER, "package", str(port_dir), "--out", str(packages)],
                cwd=root, env=env, capture_output=True, text=True, timeout=15,
            )
            if pack.returncode != 0:
                detail = (pack.stderr or pack.stdout or "Horizon Porter could not package the result.")[-5000:]
                raise HTTPException(422, detail)
        except subprocess.TimeoutExpired:
            raise HTTPException(504, "Conversion exceeded the runner time limit. Try a smaller or simpler mod.")

        artifacts = sorted([*packages.glob("*.hnmod"), *packages.glob("*.hmod")])
        if not artifacts:
            raise HTTPException(422, "Horizon Porter produced no installable package.")
        porting_notes = port_dir / "PORTING.md"
        readme = (
            "Horizon Porter generated candidate\n\n"
            "This package was generated by Horizon Porter 0.9.2 without an AI translation pass. "
            "Native Java behavior can remain as TODO stubs. Read PORTING.md before installing. "
            "A successful package step does not prove compatibility with your Starling build.\n"
        )
        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            archive.writestr("CONVERSION-STATUS.txt", readme)
            for artifact in artifacts:
                archive.write(artifact, artifact.name)
            if porting_notes.is_file():
                archive.write(porting_notes, "PORTING.md")
            notes = port_dir / "TRANSLATION-NOTES.md"
            if notes.is_file():
                archive.write(notes, "TRANSLATION-NOTES.md")

        return Response(
            content=buffer.getvalue(),
            media_type="application/zip",
            headers={
                "Content-Disposition": 'attachment; filename="horizon-porter-candidate.zip"',
                "X-Conversion-Status": "porter-generated-candidate",
                "X-Conversion-Engine": "horizon-porter-0.9.2",
                "Cache-Control": "no-store",
            },
        )
